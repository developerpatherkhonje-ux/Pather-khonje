const buildPdfBuffer = (render) => new Promise((resolve, reject) => {
  const doc = new PDFDocument({ size: 'A4', margin: 44, bufferPages: true });
  const chunks = [];
  doc.on('data', (chunk) => chunks.push(chunk));
  doc.on('end', () => resolve(Buffer.concat(chunks)));
  doc.on('error', reject);
  render(doc);
  doc.end();
});

