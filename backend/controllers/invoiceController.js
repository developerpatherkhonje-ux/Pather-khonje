const formatCurrency = (value = 0) => `Rs. ${Number(value || 0).toLocaleString('en-IN')}`;
const formatDate = (value) => {
  if (!value) return 'N/A';
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? 'N/A' : date.toLocaleDateString('en-IN');
};

