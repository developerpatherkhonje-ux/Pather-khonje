exports.addInvoicePayment = async (req, res, next) => {
  try {
    const invoice = await Invoice.findOne(applyBranchScope({ _id: req.params.id }, req.user));
    if (!invoice) return res.status(404).json({ success: false, message: 'Invoice not found' });

    const amount = Number(req.body.amount || 0);
    if (amount <= 0) {
      return res.status(400).json({ success: false, message: 'Payment amount must be greater than zero' });
    }

    if (!Number(invoice.initialAdvancePaid || 0) && (!invoice.payments || invoice.payments.length === 0) && Number(invoice.advancePaid || 0) > 0) {
      invoice.initialAdvancePaid = Number(invoice.advancePaid || 0);
    }

    const receiptNumber = `RCT${String(Date.now()).slice(-8)}`;
    invoice.payments.push({
      amount,
      date: req.body.date || new Date(),
      method: req.body.method || req.body.paymentMethod || 'Cash',
      reference: req.body.reference,
      notes: req.body.notes,
      receiptNumber,
      receivedBy: req.user?._id,
    });
    invoice.recalculatePaymentStatus();
    await invoice.save();
    const settings = await BusinessSettings.findOne({ key: 'default' }).lean();
    if (settings?.invoice?.autoSendEmail && invoice.customer?.email) {
      const payment = invoice.payments[invoice.payments.length - 1];
      createReceiptPdfAttachment(invoice, payment, settings)
        .then((pdf) => sendReceiptEmail(invoice, payment, settings.company || {}, [{
          filename: `${payment.receiptNumber || 'receipt'}.pdf`,
          content: pdf,
          contentType: 'application/pdf',
        }]))
        .catch((emailError) => {
        logger.warn('Receipt email failed', { error: emailError.message, invoiceNumber: invoice.invoiceNumber });
      });
    }

    res.status(201).json({
      success: true,
      data: {
        invoice,
        payment: invoice.payments[invoice.payments.length - 1],
      },
    });
  } catch (error) {
    next(error);
  }
};

